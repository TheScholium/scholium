/**
 * A single-line stroke font, so labels can be drawn as real ink.
 *
 * Text boxes only exist in NOTE, and they sit wherever the text engine puts
 * them. Ink labels work in NOTE and DOC, land exactly where the tick is, and
 * look like a careful hand with a technical pen.
 *
 * Units: cap height 1, baseline 0, y up. Each glyph is a list of strokes.
 * Where a glyph can be drawn in one stroke by going back over a line already
 * drawn (the stem of a 4, the crossbar of a t), it is, because each stroke
 * is one call to the tablet.
 */
import { Pt } from './types';

type Glyph = { w: number; s: Pt[][] };

function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 0): Pt[] {
  const deg = Math.PI / 180;
  const steps = n || Math.max(4, Math.ceil(Math.abs(a1 - a0) / 12));
  const out: Pt[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = (a0 + ((a1 - a0) * i) / steps) * deg;
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return out;
}

