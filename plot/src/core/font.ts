const TRACK = 0.12;

export function hasGlyph(ch: string): boolean { return ch in G; }

/** Width of a string in font units (cap height = 1). */
export function measure(text: string): number {
  let w = 0;
  for (const ch of text) w += (G[ch] ?? G[' ']).w + TRACK;
  return Math.max(0, w - TRACK);
}

/**
 * Strokes for a string, in page pixels. `size` is the cap height in px;
 * (x, y) is the left end of the baseline.
 */
export function strokes(text: string, x: number, y: number, size: number): Pt[][] {
  const out: Pt[][] = [];
  let pen = 0;
  for (const ch of text) {
    const g = G[ch] ?? G[' '];
    for (const st of g.s) out.push(st.map(([gx, gy]) => [x + (pen + gx) * size, y - gy * size] as Pt));
    pen += g.w + TRACK;
  }
  return out;
}
