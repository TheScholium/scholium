import { autoWindow } from '../src/core/zoom';
import { ok, done } from './t';
const W = (...l: string[]) => autoWindow(l, [0, 2 * Math.PI], 4 / 3)!;
const has = (r: [number, number], v: number) => r[0] < v && v < r[1];
let w = W('y = x^2 - 4');
ok(has(w.x, -2) && has(w.x, 2) && has(w.y, -4), `parabola ${w.x} ${w.y}`);
w = W('y = sin x');
ok(w.pi && Math.abs(w.x[1] - 2 * Math.PI) < 1e-9 && w.y[1] < 2, `sin ${w.x} ${w.y}`);
w = W('y = e^x');
ok(w.x[1] - w.x[0] <= 12 && w.x[0] < 0, `exp is not framed by far-off "poles": ${w.x}`);
w = W('y = 1/(x - 3)');
ok(has(w.x, 3) && w.y[1] - w.y[0] < 20, `pole ${w.x} ${w.y}`);
w = W('y = (x - 50)^2');
ok(has(w.x, 50) && w.x[1] - w.x[0] < 10, `far vertex ${w.x}`);
w = W('x^2 + y^2 = 25');
ok(has(w.x, 5) && has(w.y, 5) && w.y[1] < 8, `circle ${w.x} ${w.y}`);
ok(Math.abs((w.x[1] - w.x[0]) / (w.y[1] - w.y[0]) - 4 / 3) < 0.35, 'circle units near equal');
w = W('y = x^2', 'y = 2x + 3');
ok(has(w.x, 3) && has(w.x, -1) && has(w.y, 9), `crossings ${w.x} ${w.y}`);
w = W('r = 1 + cos θ');
ok(has(w.x, 2) && has(w.y, 1.2), `cardioid ${w.x} ${w.y}`);
ok(autoWindow(['', ''], [0, 1], 1) === null, 'nothing to frame');
done('zoom');
