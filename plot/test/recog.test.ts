import { cleanRecognized } from '../src/core/recog';
import { ok, done } from './t';
const c = (s: string) => cleanRecognized(s).join(' | ');
ok(c('y=x2-4') === 'y=x^2-4', c('y=x2-4'));
ok(c('Y = 2x + 1') === 'y = 2x + 1', c('Y = 2x + 1'));
ok(c('y = (x+1)2') === 'y = (x+1)^2', c('y = (x+1)2'));
ok(c('y = sin x\ny = cos x') === 'y = sin x | y = cos x', 'two lines');
ok(c('y = log2 x') === 'y = log2 x', c('y = log2 x'));
ok(c('y = 3 X 4') === 'y = 3*4', c('y = 3 X 4'));
ok(c('x2 + y2 = 9') === 'x^2 + y^2 = 9', c('x2 + y2 = 9'));
done('recog');
