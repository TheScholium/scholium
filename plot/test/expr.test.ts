import { compile, parseEquation, evalNumber, normalize } from '../src/core/expr';
import { ok, near, throws, done } from './t';

const f = (s: string, x = 0, y = 0, t = 0) => compile(s, ['x', 'y', 't', 'theta']).fn({ x, y, t, theta: t });

near(f('2x^2 - 3x + 1', 2), 3, 'poly');
near(f('-x^2', 3), -9, 'unary minus below power');
near(f('2^-1'), 0.5, 'negative exponent');
near(f('2^3^2'), 512, 'right assoc');
near(f('sin x cos x', 0.3), Math.sin(0.3) * Math.cos(0.3), 'sin x cos x');
near(f('sin^2 x + cos^2 x', 1.1), 1, 'sin^2');
near(f('sin(x)^2', 1.1), Math.sin(1.1) ** 2, 'sin(x)^2');
near(f('2pi'), 2 * Math.PI, '2pi');
near(f('2πx', 0.5), Math.PI, '2πx');
near(f('xy', 2, 3), 6, 'xy');
near(f('(x+1)(x-1)', 3), 8, 'product of parens');
near(f('|x - 3|', 1), 2, 'abs bars');
near(f('2|x|+1', -2), 5, 'abs implicit');
near(f('5!'), 120, 'factorial');
near(f('x^(1/3)', -8), -2, 'real cube root');
near(f('x^(2/3)', -8), 4, 'even numerator root');
near(f('e^(-x^2/2)', 1), Math.exp(-0.5), 'gaussian');
near(f('ln e'), 1, 'ln e');
near(f('log 100'), 2, 'log10');
near(f('√(x)', 9), 3, 'sqrt symbol');
near(f('x²', 4), 16, 'superscript');
near(f('3·x', 2), 6, 'dot');
near(f('1/2x', 4), 2, '1/2x is (1/2)x');
near(f('max(x, 2)', 1), 2, 'two-arg');
near(f('2e', 0), 2 * Math.E, '2e is 2 times e');
near(f('1e3'), 1000, 'scientific');
near(f('[x+1]^2', 1), 4, 'brackets');
near(f('sinc(0)'), 1, 'sinc');
near(f('gamma(5)'), 24, 'gamma', 1e-12);
near(f('-2^2'), -4, '-2^2');
throws(() => f('2 + '), 'dangling');
throws(() => f('foo(x)'), 'unknown name');
throws(() => f('(x'), 'paren');
near(evalNumber('-pi/2'), -Math.PI / 2, 'evalNumber');
ok(normalize('y = x² − 1') === 'y = x^2 - 1', 'normalize');

const k = (s: string) => parseEquation(s).kind;
ok(k('y = x^2') === 'function', 'y=');
ok(k('x^2') === 'function', 'bare');
ok(k('f(x) = sin x') === 'function', 'f(x)=');
ok(k('x = y^2') === 'xfunction', 'x=g(y)');
ok(k('x = 3') === 'vertical', 'vertical');
ok(k('r = 1 + cos θ') === 'polar', 'polar');
ok(k('x^2 + y^2 = 4') === 'implicit', 'implicit');
ok(k('y = x y') === 'implicit', 'y on both sides');
ok(k("y' = x - y") === 'slope', 'slope');
ok(k('dy/dx = y') === 'slope', 'dy/dx');
ok(k('(cos t, sin t)') === 'parametric', 'tuple');
ok(k('x = cos 3t, y = sin 2t') === 'parametric', 'x=, y=');
ok(k('(x+1)(x-1)') === 'function', 'not a tuple');
throws(() => parseEquation('x^2 + y^2'), 'needs =');
throws(() => parseEquation('a = b = c'), 'two =');
const P = parseEquation('(cos t, sin t)');
if (P.kind === 'parametric') near(P.x({ t: 0 }), 1, 'param x');
const pol = parseEquation('r = 2 sin θ');
if (pol.kind === 'polar') near(pol.f({ theta: Math.PI / 2, t: Math.PI / 2 }), 2, 'polar value');
done('expr');
const sl = parseEquation("y' = -y, y(0) = 2");
ok(sl.kind === 'slope' && sl.init![0] === 0 && sl.init![1] === 2, 'initial value');
throws(() => parseEquation('y = x, y(0) = 2'), 'IC needs slope');
done('expr+ic');
near(f('cos 3t', 0, 0, 0.5), Math.cos(1.5), 'cos 3t');
near(f('sin 2x y', 0.3, 2), Math.sin(1.2), 'sin 2xy');
near(f('sin^2 x cos x', 0.7), Math.sin(0.7) ** 2 * Math.cos(0.7), 'sin^2 x cos x');
near(f('sin -x', 0.7), -Math.sin(0.7), 'sin -x');
near(f('ln 2x + 1', 3), Math.log(6) + 1, 'ln 2x + 1');
near(f('2 sin x', 0.7), 2 * Math.sin(0.7), '2 sin x');
near(f('sin x / x', 0.7), Math.sin(0.7) / 0.7, 'sin x / x');
done('expr+funcarg');
